/**
 * Получить термин по slug
 */
export function getGlossaryTerm(slug: string): GlossaryTerm | undefined {
  return GLOSSARY.find((t) => t.slug === slug);
}

/**
 * Получить все термины определённой категории
 */
export function getGlossaryByCategory(
  category: GlossaryTerm["category"]
): GlossaryTerm[] {
  return GLOSSARY.filter((t) => t.category === category);
}

/**
 * Получить все slugs для статической генерации страниц
 */
export function getAllGlossarySlugs(): string[] {
  return GLOSSARY.map((t) => t.slug);
}

/**
 * Поиск терминов по строке
 */
export function searchGlossary(query: string): GlossaryTerm[] {
  const q = query.toLowerCase();
  return GLOSSARY.filter(
    (t) =>
      t.term.toLowerCase().includes(q) ||
      t.definition.toLowerCase().includes(q) ||
      t.title.toLowerCase().includes(q)
  );
}
